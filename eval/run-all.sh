#!/usr/bin/env bash
# Regenerates every evaluation result in docs/evaluation/ (brief §6).
# Usage: eval/run-all.sh            (about 2–3 minutes on an M-series Mac)
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=docs/evaluation
mkdir -p "$OUT"

echo "delta efficiency and resume..."
cargo run -q --release -p nebula-tests --bin eval >"$OUT/delta-and-resume.md"

echo "large files over real daemons..."
eval/large-files.sh 1 100 1024 >"$OUT/large-files.md"

# Test suites: record each test's name and result.
suite() { # title, cargo test args...
  local title=$1
  shift
  echo "## $title"
  echo
  echo "| Test | Result |"
  echo "|---|---|"
  cargo test -q --release "$@" -- --test-threads=1 --format=pretty 2>/dev/null |
    grep -E '^test .* \.\.\. ' |
    sed -E 's/^test ([^ ]+) \.\.\. (ok|FAILED|ignored).*/| `\1` | \2 |/'
  echo
}

echo "correctness, conflict and security suites..."
{
  echo "# Nebula evaluation: correctness, conflicts and security"
  echo
  echo "Generated by \`eval/run-all.sh\`. Convergence uses 1000 random cases."
  echo
  PROPTEST_CASES=1000 suite "Sync correctness and conflict handling (two engines, real folders)" \
    -p nebula-sync --test sync
  suite "Security (real TCP through the fault-injection proxy)" -p nebula-tests --test security
  suite "Pairing (SPAKE2 + Noise XXpsk2)" -p nebula-net pairing
  suite "Encrypted sessions (Noise XX)" -p nebula-net transport
} >"$OUT/correctness-and-security.md"

{
  echo "# Evaluation results"
  echo
  echo "- Commit: \`$(git rev-parse --short HEAD)\`"
  echo "- Date: $(date +%Y-%m-%d)"
  echo "- Machine: $(sysctl -n machdep.cpu.brand_string 2>/dev/null || uname -m), \
$(($(sysctl -n hw.memsize 2>/dev/null || echo 0) / 1073741824)) GiB RAM, $(uname -s) $(sw_vers -productVersion 2>/dev/null || uname -r)"
  echo "- Rust: $(rustc --version)"
  echo
  echo "| Brief §6 evaluation | Result file |"
  echo "|---|---|"
  echo "| Sync correctness (random operations converge) | [correctness-and-security.md](correctness-and-security.md) |"
  echo "| Delta efficiency (bytes sent vs. file size) | [delta-and-resume.md](delta-and-resume.md) |"
  echo "| Conflict handling (no bytes lost) | [correctness-and-security.md](correctness-and-security.md) |"
  echo "| Large files (1 MiB, 100 MiB, 1 GiB; throughput, memory) | [large-files.md](large-files.md) |"
  echo "| Dropped connections (resume) | [delta-and-resume.md](delta-and-resume.md), [large-files.md](large-files.md) |"
  echo "| Security | [correctness-and-security.md](correctness-and-security.md) |"
  echo
  echo "Regenerate with \`eval/run-all.sh\`."
} >"$OUT/README.md"

echo "done: $OUT/"
